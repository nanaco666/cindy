#!/usr/bin/env node
/**
 * sync-lark-tools.mjs
 * ---------------------------------------------------------------------------
 * Vendors the official Feishu/Lark OpenAPI tool definitions from
 * `larksuite/lark-openapi-mcp` (MIT) into this package, so our hand-written
 * Feishu MCP can offer full OpenAPI coverage by dispatching the vendored defs
 * through OUR auth + progressive-disclosure layer (see mcp/genTools.ts).
 *
 * What it pulls: `src/mcp-tool/tools/en/gen-tools/zod/*.ts` (one file per API
 * domain; pure data — `import { z }` + per-tool const objects + a `<domain>Tools`
 * array). We only consume the arrays.
 *
 * Output (all under src/feishu/mcp/generated/, DO NOT hand-edit):
 *   - zod/<domain>.ts        verbatim upstream + a provenance/MIT header
 *   - index.ts               aggregates every `<domain>Tools` into `GEN_TOOLS`
 *   - version.ts             pinned upstream ref
 *   - LICENSE.lark-openapi-mcp  upstream MIT license text
 *
 * Usage:  node scripts/sync-lark-tools.mjs [--version vX.Y.Z]
 * Requires: `gh` CLI authenticated (uses `gh api`).
 */
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'larksuite/lark-openapi-mcp';
const ZOD_DIR = 'src/mcp-tool/tools/en/gen-tools/zod';

const argv = process.argv.slice(2);
const verIdx = argv.indexOf('--version');
const REF = verIdx >= 0 ? argv[verIdx + 1] : 'v0.5.1';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, '../src/feishu/mcp/generated');
const OUT_ZOD = path.join(OUT, 'zod');

/** Run `gh api <route>` and return parsed JSON. */
function gh(route) {
  const out = execFileSync('gh', ['api', route], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(out);
}

/**
 * Fetch a repo file's decoded UTF-8 content at REF.
 * The contents API returns empty `content` for files >1MB, so fall back to the
 * blob API (handles up to 100MB) keyed by the sha the contents API still gives.
 */
function ghFile(repoPath) {
  const res = gh(`repos/${REPO}/contents/${repoPath}?ref=${REF}`);
  if (res.content && res.content.length > 0) {
    return Buffer.from(res.content, 'base64').toString('utf8');
  }
  if (res.sha) {
    const blob = gh(`repos/${REPO}/git/blobs/${res.sha}`);
    return Buffer.from(blob.content, 'base64').toString('utf8');
  }
  throw new Error(`empty content and no sha for ${repoPath}`);
}

function header(domainFile) {
  return [
    '/**',
    ` * VENDORED from ${REPO} @ ${REF}`,
    ` * Source: ${ZOD_DIR}/${domainFile}`,
    ' * License: MIT — Copyright (c) 2025 Lark Technologies Pte. Ltd.',
    ' *          (full text in ../LICENSE.lark-openapi-mcp)',
    ' * DO NOT EDIT BY HAND. Regenerate: node packages/lizi-mcps/scripts/sync-lark-tools.mjs',
    ' */',
    '',
  ].join('\n');
}

function main() {
  console.log(`[sync-lark-tools] repo=${REPO} ref=${REF}`);
  fs.mkdirSync(OUT_ZOD, { recursive: true });

  // 1. Enumerate the zod domain files at REF.
  const tree = gh(`repos/${REPO}/git/trees/${REF}?recursive=1`);
  const files = tree.tree
    .map((t) => t.path)
    .filter((p) => new RegExp(`^${ZOD_DIR}/[^/]+\\.ts$`).test(p))
    .sort();
  console.log(`[sync-lark-tools] found ${files.length} domain files`);

  // 2. Vendor each file, capturing its exported `<domain>Tools` array name.
  const imports = [];
  let toolDefCount = 0;
  for (const repoPath of files) {
    const base = path.basename(repoPath); // e.g. minutes_v1.ts
    const raw = ghFile(repoPath);
    const m = raw.match(/export const (\w+Tools)\s*=/);
    if (!m) {
      console.warn(`[sync-lark-tools] SKIP ${base}: no *Tools export found`);
      continue;
    }
    const arrayName = m[1];
    // Rough count of tool defs for the summary (each has a `name:` field).
    toolDefCount += (raw.match(/\bname: '/g) || []).length;
    fs.writeFileSync(path.join(OUT_ZOD, base), header(base) + raw, 'utf8');
    imports.push({ arrayName, module: `./zod/${base.replace(/\.ts$/, '.js')}` });
  }

  // 3. generated/index.ts — aggregate all arrays into GEN_TOOLS.
  const indexLines = [
    '// AUTO-GENERATED by scripts/sync-lark-tools.mjs — DO NOT EDIT.',
    '// Aggregates every vendored `<domain>Tools` array into a single GEN_TOOLS list.',
    ...imports.map((i) => `import { ${i.arrayName} } from '${i.module}';`),
    '',
    'export const GEN_TOOLS = [',
    ...imports.map((i) => `  ...${i.arrayName},`),
    '];',
    '',
  ];
  fs.writeFileSync(path.join(OUT, 'index.ts'), indexLines.join('\n'), 'utf8');

  // 4. generated/version.ts — provenance.
  fs.writeFileSync(
    path.join(OUT, 'version.ts'),
    [
      '// AUTO-GENERATED by scripts/sync-lark-tools.mjs — DO NOT EDIT.',
      `export const LARK_MCP_VENDOR_SOURCE = '${REPO}';`,
      `export const LARK_MCP_VENDOR_REF = '${REF}';`,
      '',
    ].join('\n'),
    'utf8',
  );

  // 5. Vendor the upstream LICENSE.
  try {
    const license = ghFile('LICENSE');
    fs.writeFileSync(path.join(OUT, 'LICENSE.lark-openapi-mcp'), license, 'utf8');
  } catch {
    console.warn('[sync-lark-tools] could not fetch LICENSE');
  }

  console.log(
    `[sync-lark-tools] wrote ${imports.length} domain files, ~${toolDefCount} tool defs → ${path.relative(process.cwd(), OUT)}`,
  );
}

main();
